async function main() {
  console.log("Enriching language lessons with accurate Arabic definitions translations...");

  for (const [lessonId, definitions] of Object.entries(DEFINITIONS_MAP)) {
    const summary = await prisma.lessonSummary.findFirst({
      where: { lessonId }
    });

    if (summary) {
      await prisma.lessonSummary.update({
        where: { id: summary.id },
        data: { definitions }
      });
      console.log(`Updated summary for lesson ${lessonId} with ${definitions.length} translated definitions.`);
    } else {
      await prisma.lessonSummary.create({
        data: {
          lessonId,
          keyConcepts: [],
          definitions
        }
      });
      console.log(`Created summary for lesson ${lessonId} with ${definitions.length} translated definitions.`);
    }
  }

  console.log("Definitions enrichment complete!");
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());

